def reply_keyboard(rows):
    """Формат reply_markup для Telegram."""
    return {
        "keyboard": [[{"text": label} for label in row] for row in rows],
        "resize_keyboard": True,
        "is_persistent": True,
    }


def resolve(text):
    """
    Разбирает нажатие кнопки.

    Возвращает (команда, клавиатура, готовый_ответ). Любое поле может быть None:
      — команда: подставить вместо текста и выполнить как обычно;
      — клавиатура и ответ: показать подменю;
      — всё None: это не кнопка, обрабатывать как обычный текст.
    """
    text = (text or "").strip()

    if text in COMMANDS:
        return COMMANDS[text], None, None

    if text in SUBMENUS:
        return None, reply_keyboard(SUBMENUS[text]), SUBMENU_TEXT.get(text, "Выберите пункт")

    if text == "➕ Добавить маршрут":
        return None, reply_keyboard(MAIN), ADD_ROUTE_HELP

    return None, None, None
